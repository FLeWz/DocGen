"""DOCX import e2e against a running stack:
  PLAYWRIGHT_BROWSERS_PATH=$PWD/.playwright .venv/bin/python e2e/import.py   (E2E_BASE_URL, default http://localhost:8080)
Upload the fixture DOCX -> warnings panel -> create snippet from selection -> use as base document -> commit snippet ->
document on that base -> download DOCX (custom style + header kept) -> export the edited import (package parts kept).
Needs `docker compose` (the fixture is generated by the api image); logs in as a throwaway user from scripts/e2e-users.sh."""
import os
import re
import shutil
import subprocess
import zipfile

from playwright.sync_api import expect, sync_playwright

from common import ART, commit, commit_from_editor, editor_ready, login, new_folder, new_item, open_folder, open_item, saved, user

email, password, _ = user("import")

os.makedirs(ART, exist_ok=True)
sample = os.path.join(ART, "import-sample.docx")
if os.environ.get("E2E_SAMPLE_DOCX"):  # set in the e2e container, which has no docker
    shutil.copy(os.environ["E2E_SAMPLE_DOCX"], sample)
else:
    with open(sample, "wb") as f:
        f.write(subprocess.run(["docker", "compose", "run", "--rm", "--no-deps", "-T", "api", "python", "-m",
                                "tests.fixtures.sample", "-"], capture_output=True, check=True).stdout)


def part(path, name):
    return zipfile.ZipFile(path).read(name).decode()


with sync_playwright() as pw:
    browser = pw.chromium.launch(headless=True)
    page = browser.new_page(viewport={"width": 1700, "height": 1000}, accept_downloads=True)
    try:
        login(page, email, password)
        new_folder(page, "Imported")

        # upload (dropzone input) -> editor with the document, warnings panel lists what is not editable
        page.get_by_role("link", name="Imports").click()
        page.get_by_label("DOCX file").set_input_files(sample)
        expect(page).to_have_url(re.compile("/imports/"))
        ed = editor_ready(page)
        expect(ed.get_by_text("Callout paragraph with a custom style")).to_be_visible()
        w = page.get_by_test_id("import-warnings")
        expect(w).to_contain_text("not editable")
        expect(w.locator("li")).to_have_count(0)  # collapsed by default: one line, the list is not even rendered
        assert w.bounding_box()["height"] < 45
        w.get_by_role("button").click()
        expect(w.locator("li").first).to_be_visible()
        expect(w).to_contain_text("tracked insertion")  # round 24: the text box and the block content control are editable nodes, not warnings
        expect(w).not_to_contain_text("text box")
        expect(ed.locator(".opaque-view")).to_have_count(0)
        expect(ed.locator(".txbx")).to_have_count(1)
        expect(ed.locator(".sdtb")).to_have_count(1)
        expect(ed.get_by_text("INSERTED-MARKER")).to_be_visible()
        expect(ed.get_by_text("TEXTBOX-MARKER")).to_be_visible()
        expect(ed.get_by_text("SDT-CONTENT-MARKER")).to_be_visible()
        expect(page.locator(".docx-hdr").first).to_contain_text("HEADER-MARKER")  # header/footer of the DOCX on the page
        expect(page.locator(".docx-ftr").first).to_contain_text("FOOTER-MARKER")
        page.get_by_label("Preview mode").select_option("word")  # real exporter + LibreOffice
        expect(page.get_by_test_id("word-pdf")).to_be_visible(timeout=90_000)
        page.get_by_label("Preview mode").select_option("live")

        # edit directly (autosaved), then create a snippet from the selection (cursor block = the Callout paragraph)
        ed.get_by_text("The end.").click()
        page.keyboard.press("End")
        page.keyboard.type(" EDITED")
        saved(page)
        ed.get_by_text("Callout paragraph with a custom style").click()
        page.get_by_role("button", name="Create snippet from selection").click()
        page.get_by_label("Snippet title").fill("Callout")
        page.get_by_role("button", name="Create snippet", exact=True).click()
        expect(page.get_by_text('Created snippet draft "Callout"')).to_be_visible()

        # split: individual headings (default = level 1), shortcuts, two non-adjacent headings, edited title
        page.get_by_role("button", name="Split by headings").click()
        pv = page.get_by_test_id("split-preview")
        expect(pv.locator("li")).to_have_count(4)
        page.get_by_role("button", name="Level 1–2").click()
        expect(pv.locator("li")).to_have_count(5)
        page.get_by_role("button", name="None", exact=True).click()
        expect(pv.locator("li")).to_have_count(0)
        page.get_by_role("button", name="Cancel").click()  # applied at the end, so the commit steps below see only the Callout draft

        # use as base document (owner = admin)
        page.get_by_role("button", name="Use as base document").click()
        page.get_by_label("Base document name").fill("From import")
        page.get_by_role("button", name="Save as base document").click()
        expect(page.get_by_text('Saved as base document "From import"')).to_be_visible()
        # same name again (other case): asked whether to create a new version instead
        page.get_by_role("button", name="Use as base document").click()
        page.get_by_label("Base document name").fill("from IMPORT")
        page.get_by_role("button", name="Save as base document").click()
        expect(page.get_by_test_id("name-conflict")).to_contain_text("A base document named From import already exists")
        page.get_by_role("button", name="Create new version").click()
        expect(page.get_by_text('Saved as version 2 of base document "From import"')).to_be_visible()

        # export the edited import: original package kept, edit present
        with page.expect_download(timeout=30_000) as dl:
            page.get_by_role("button", name="Export DOCX").click()
        exp = os.path.join(ART, "import-export.docx")
        dl.value.save_as(exp)
        assert "EDITED" in part(exp, "word/document.xml")
        assert "TEXTBOX-MARKER" in part(exp, "word/document.xml") and "SDT-CONTENT-MARKER" in part(exp, "word/document.xml")
        assert 'w:styleId="Callout"' in part(exp, "word/styles.xml")
        assert "HEADER-MARKER" in part(exp, "word/header1.xml") and "FOOTER-MARKER" in part(exp, "word/footer1.xml")

        # separate pages: grow the document past one page (blank paragraphs) -> page gaps appear, each page has header + footer
        ed.get_by_text("The end.").click()
        page.keyboard.press("End")
        for _ in range(70):
            page.keyboard.press("Enter")
        expect(ed.locator(".pgsep").first).to_be_attached(timeout=10_000)
        assert page.locator(".pgsep .docx-hdr").count() >= 1 and page.locator(".pgsep .docx-ftr").count() >= 1, "page gap lacks header/footer"
        expect(page.get_by_test_id("page-count")).to_contain_text("pages")
        page.keyboard.type(" STILL-TYPING")  # editing keeps working across the page gap
        expect(ed.get_by_text("STILL-TYPING")).to_be_visible()
        page.get_by_label("Zoom").select_option("0.4")  # preview: separate paper cards, each with header and footer
        cards = page.get_by_test_id("preview").locator(".docx-page")
        assert cards.count() >= 2, "preview is one continuous page"
        assert page.get_by_test_id("preview").locator(".docx-hdr").count() >= 2 and page.get_by_test_id("preview").locator(".docx-ftr").count() >= 2

        # commit the new snippet, use it in a document built on the imported base document
        open_folder(page, "Imported")
        open_item(page, "Callout")
        commit_from_editor(page, "from import")
        open_folder(page, "Imported")
        new_item(page, "document", "Report")
        expect(page.get_by_label("Document title")).to_have_value("Report")
        page.get_by_label("Base document", exact=True).select_option(label="From import")
        page.get_by_role("button", name="Add Callout").click()
        saved(page, "doc-save-status")
        with page.expect_download(timeout=60_000) as dl:
            page.get_by_role("button", name="Download DOCX").click()
        out = os.path.join(ART, "import-report.docx")
        dl.value.save_as(out)
        doc = part(out, "word/document.xml")
        assert "Callout paragraph with a custom style" in doc and 'w:pStyle w:val="Callout"' in doc, "style id lost"
        assert 'w:styleId="Callout"' in part(out, "word/styles.xml") and "HEADER-MARKER" in part(out, "word/header1.xml")
        # apply the split: two non-adjacent headings (the one between them merges into the first), one renamed
        page.get_by_role("link", name="Imports", exact=True).click()
        page.locator("a.titlelink").first.click()
        page.get_by_role("button", name="Split by headings").click()
        pv = page.get_by_test_id("split-preview")
        page.get_by_role("button", name="None", exact=True).click()
        page.get_by_label("Split at Introduction").check()
        page.get_by_label("Split at Merged cells").check()
        expect(pv.locator("li")).to_have_count(2)
        page.get_by_label("Snippet title for Introduction").fill("Intro part")
        expect(pv.locator("li").first).to_contain_text("Intro part")
        page.get_by_role("button", name="Create 2 snippets").click()
        expect(page.get_by_text("Created 2 snippet drafts")).to_be_visible()
        open_folder(page, "Imported")
        expect(page.get_by_test_id("item-row").filter(has_text="Intro part")).to_be_visible()
        titles = page.get_by_test_id("item-row").all_inner_texts()
        assert any("Intro part" in t for t in titles) and any("Merged cells" in t for t in titles) and not any("Revision history" in t for t in titles), titles
        print("e2e import OK")
    except Exception:
        page.screenshot(path=f"{ART}/import-failure.png", full_page=True)
        raise
    finally:
        browser.close()
